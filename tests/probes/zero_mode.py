import numpy as np
from scipy import sparse
from scipy.sparse.linalg import eigsh

import _bootstrap  # noqa: E402,F401


def skyrmion_profile(r, size=1.5, winding=1):
    """The exact radial angle used by substrate3d.texture_state.

    The sign reverses the target-space orientation while preserving the
    boundary value modulo 2*pi.
    """
    return winding * np.pi * np.exp(-r / size)


def radial_hamiltonian(r, h, winding=1, size=1.5):
    """Hermitian grand-spin-zero Skyrmion-Dirac Hamiltonian.

    p=r*u and q=r*v have the flat dr inner product.  Dirichlet values at
    r=0 and r=R are outside the interior grid.  A forward/backward
    adjoint pair avoids the centered-difference doubler; the two
    off-diagonal blocks are exact discrete adjoints.
    """
    n = len(r)
    dr = float(r[1] - r[0])
    deriv = sparse.diags(
        (-np.ones(n) / dr, np.ones(n - 1) / dr),
        (0, 1), shape=(n, n), format="csr")

    F = skyrmion_profile(r, size=size, winding=winding)
    radial = sparse.diags(1.0 / r + h * np.sin(F), format="csr")
    mass = sparse.diags(h * np.cos(F), format="csr")
    upper = deriv + radial
    lower = upper.T
    return sparse.bmat([[-mass, upper], [lower, mass]], format="csr")


def near_zero_states(H, r, count=12):
    """Eigenpairs nearest zero, with radial localization diagnostics."""
    n = len(r)
    values, vectors = eigsh(H, k=count, sigma=0.0, which="LM")
    order = np.argsort(values)
    states = []
    for idx in order:
        psi = vectors[:, idx]
        density = psi[:n] ** 2 + psi[n:] ** 2
        density /= density.sum()
        states.append({
            "energy": float(values[idx]),
            "r_mean": float(np.sum(r * density)),
            "core_weight": float(density[r < 3.0].sum()),
        })
    return states


def localized_level(r, h, winding=1, size=1.5):
    """The most core-localized in-gap state near zero."""
    H = radial_hamiltonian(r, h, winding=winding, size=size)
    states = near_zero_states(H, r)
    in_gap = [s for s in states if abs(s["energy"]) < 0.98 * abs(h)]
    candidates = in_gap or states
    return max(candidates, key=lambda s: (s["core_weight"], -s["r_mean"]))


def run(report=print):
    size, R, n = 1.5, 18.0, 300
    dr = R / (n + 1)
    r = dr * np.arange(1, n + 1)

    # A diagnostic spectral family, not a parameter selection. In this sign
    # convention h < 0 is the crossing parity branch for the chosen winding.
    couplings = np.linspace(-0.5, -2.0, 11)
    levels = [localized_level(r, h, size=size) for h in couplings]
    energies = np.array([s["energy"] for s in levels])

    crossing_intervals = []
    for i in range(len(couplings) - 1):
        if energies[i] == 0 or energies[i] * energies[i + 1] < 0:
            crossing_intervals.append((float(couplings[i]),
                                       float(couplings[i + 1])))

    report("SKYRMION-DIRAC SPECTRAL FLOW ON THE 3D KNOT")
    report("=" * 68)
    report("  U = cos F + i sin F r_hat.sigma,  F = pi exp(-r/1.5)")
    report("  grand-spin-zero radial Hamiltonian; h is scanned, not fitted")
    report(f"  {'h':>8s} {'omega':>12s} {'omega/|h|':>12s} "
           f"{'<r>':>8s} {'core wt':>9s}")
    for h, state in zip(couplings, levels):
        report(f"  {h:>+8.3f} {state['energy']:>+12.5f} "
               f"{state['energy']/abs(h):>+12.5f} "
               f"{state['r_mean']:>8.3f} {state['core_weight']:>9.3f}")

    assert len(crossing_intervals) == 1, \
        "the degree-one diagnostic family must show one tracked crossing"
    assert np.all(np.diff(energies) < 0), \
        "the tracked localized level must flow monotonically"
    assert min(s["core_weight"] for s in levels) > 0.5, \
        "the tracked spectral-flow branch must remain core-localized"

    # The sign change is not a grid artifact.  A coarser radial grid gives
    # the same signs and nearby energies at the crossing bracket.
    n_coarse = 240
    dr_coarse = R / (n_coarse + 1)
    r_coarse = dr_coarse * np.arange(1, n_coarse + 1)
    i_cross = next(i for i in range(len(energies) - 1)
                   if energies[i] * energies[i + 1] < 0)
    coarse = np.array([
        localized_level(r_coarse, couplings[i], size=size)["energy"]
        for i in (i_cross, i_cross + 1)
    ])
    fine = energies[i_cross:i_cross + 2]
    assert coarse[0] * fine[0] > 0 and coarse[1] * fine[1] > 0
    assert np.max(np.abs(coarse - fine)) < 0.02

    report("-" * 68)
    lo, hi = crossing_intervals[0]
    report(f"  one localized level crosses zero for h in [{lo:.3f}, {hi:.3f}]")
    report("  => unit winding is witnessed by ONE NET SPECTRAL CROSSING")
    report("  => the scan witnesses the unit-winding index/spectral flow")
    report("  => h labels this spectral family; it is not a fitted input")
    report("  closure chirality and gauge representations enter through")
    report("  their separately derived branches and stated identification")

    return {
        "profile": "F(r)=pi*exp(-r/1.5)",
        "couplings": couplings,
        "levels": levels,
        "crossing_intervals": crossing_intervals,
        "net_crossings": len(crossing_intervals),
        "crossing_converged": True,
        "scan_role": "spectral-family coordinate",
        "enters_scorecard": False,
        "pinned_zero_mode": False,
    }


if __name__ == "__main__":
    run()
