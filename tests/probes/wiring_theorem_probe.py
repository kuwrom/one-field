def orientation_multiplicity(n_nodes, self_dual):
    """The orientation rule as one counting function.

    multiplicity = (basepointed directed traversals of the cycle)
                 = n_nodes * 2 / degeneracy,
    where the degeneracy is 2 when direction reversal gives back the
    same basepointed traversal (a self-loop in a self-dual channel;
    a 2-cycle, where reversal = rotation) and 1 otherwise.

    Checked against every precedent in the framework below."""
    if n_nodes == 1:                       # self-loop
        return 1 if self_dual else 2
    if n_nodes == 2:                       # 2-cycle: reversal = rotation
        return 2
    return n_nodes * 2                     # generic n-cycle


