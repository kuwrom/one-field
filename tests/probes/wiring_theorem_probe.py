def albert_unital_response(n26=26, schur_weight=Fraction(1, 2)):
    """The recursive Albert transport includes and fixes its unit."""
    p1 = np.zeros((n26 + 1, n26 + 1))
    p1[0, 0] = 1.0
    p26 = np.eye(n26 + 1) - p1
    unit = np.zeros(n26 + 1)
    unit[0] = 1.0

    options = {
        a: schur_weight * Fraction(round(np.trace(a * p1 + p26)))
        for a in (0, 1)
    }
    assert np.allclose(p26 @ unit, 0.0)
    transport = p1 + p26
    assert np.allclose(transport @ unit, unit)
    junction = Fraction(1)  # reverse path composes as g^-1 g
    return dict(options=options, junction=junction,
                response=schur_weight
                * Fraction(round(np.trace(transport))))


