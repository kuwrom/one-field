def _reflection(alpha, G):
    """Matrix of the reflection s_alpha in simple-root coordinates."""
    n = len(alpha)
    M = np.eye(n)
    a = np.array(alpha, dtype=float)
    na = a @ G @ a
    for j in range(n):
        e = np.zeros(n)
        e[j] = 1.0
        M[:, j] = e - 2.0 * (e @ G @ a) / na * a
    return M


def _weyl_group(simples, G):
    """Reflection closure: the full Weyl group as matrices."""
    gens = [_reflection(s, G) for s in simples]
    seen = {}
    frontier = [np.eye(len(simples))]
    seen[frontier[0].round(9).tobytes()] = frontier[0]
    while frontier:
        new = []
        for w in frontier:
            for g in gens:
                m = g @ w
                key = m.round(9).tobytes()
                if key not in seen:
                    seen[key] = m
                    new.append(m)
        frontier = new
    return list(seen.values())


def _root_system(simples, G):
    """All roots by reflection closure on the simple roots."""
    W = _weyl_group(simples, G)
    roots = {}
    for w in W:
        for s in simples:
            r = w @ np.array(s, dtype=float)
            roots[tuple(r.round(9))] = r
    return list(roots.values()), W


def _fundamental_weights(G):
    """omega_i with 2(omega_i, alpha_j)/(alpha_j,alpha_j) = delta_ij,
    in simple-root coordinates."""
    n = G.shape[0]
    A = np.zeros((n, n))
    for i in range(n):
        e = np.zeros(n)
        e[i] = 1.0
        for j in range(n):
            f = np.zeros(n)
            f[j] = 1.0
            A[i, j] = 2.0 * (e @ G @ f) / (f @ G @ f)
    # weight lambda = sum_i c_i omega_i  <->  Cartan-pairing coords c
    return np.linalg.inv(A.T)          # columns = omega_i in root coords


def wzw_level1_data(name, gram):
    """S-matrix, spins, quantum dims, central charge for X(1)."""
    G = np.array(gram, dtype=float)
    n = G.shape[0]
    simples = [tuple(1.0 if j == i else 0.0 for j in range(n))
               for i in range(n)]
    roots, W = _root_system(simples, G)
    Om = _fundamental_weights(G)
    rho = Om.sum(axis=1)
    # highest root: maximal height, long (norm 2 after our normalisation)
    theta = max(roots, key=lambda r: r.sum())
    ntheta = theta @ G @ theta
    assert abs(ntheta - 2.0) < 1e-9, "normalise the Gram so long^2 = 2"
    hv = int(round(rho @ G @ theta)) + 1          # dual Coxeter number
    dim_g = len(roots) + n
    k = 1
    kappa = k + hv
    # level-1 primaries: dominant weights with (lambda, theta) <= 1
    prims = []
    for coeffs in product(range(2), repeat=n):
        lam = Om @ np.array(coeffs, dtype=float)
        if lam @ G @ theta <= 1.0 + 1e-9:
            prims.append((coeffs, lam))
    # Kac-Peterson (unnormalised), then unitarise by column norm
    S = np.zeros((len(prims), len(prims)), dtype=complex)
    dets = [round(float(np.linalg.det(w))) for w in W]
    for a, (_, la) in enumerate(prims):
        for b, (_, lb) in enumerate(prims):
            S[a, b] = sum(d * cmath.exp(-2j * math.pi *
                                        ((w @ (la + rho)) @ G @ (lb + rho))
                                        / kappa)
                          for w, d in zip(W, dets))
    S = S / math.sqrt(float(np.sum(np.abs(S[:, 0])**2)))
    if S[0, 0].real < 0:
        S = -S
    h = [float((la @ G @ (la + 2 * rho)) / (2.0 * kappa))
         for _, la in prims]
    d = [float((S[0, i] / S[0, 0]).real) for i in range(len(prims))]
    c = float(k * dim_g / kappa)
    # central charge read back from the Gauss sum (a CHECK, not input)
    Dtot = math.sqrt(sum(x * x for x in d))
    p_plus = sum(dd * dd * cmath.exp(2j * math.pi * hh)
                 for dd, hh in zip(d, h))
    c_gauss = (cmath.phase(p_plus / Dtot) / (2 * math.pi)) * 8.0
    assert abs((c_gauss - c + 4) % 8 - 4) < 1e-7, (name, c, c_gauss)
    return dict(name=name, W_order=len(W), n_roots=len(roots), hv=hv,
                dim=dim_g, prims=[p for p, _ in prims], S=S, h=h, d=d, c=c)


