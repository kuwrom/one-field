def _normalise(path):
    p = (path.replace("↔", "<->").replace("→", "->")
             .replace("₂", "2").replace("₄", "4")
             .replace("₃", "3").replace("₀", "0")
             .replace("₁", "1").replace("×", "x")
             .replace("₅", "5").replace("₆", "6")
             .replace("ₕ", "").replace("ᵥ", ""))
    return p


def classify(path):
    p = _normalise(path)
    if "self-echo" in p or ("share" in p and "F4" in p):
        return EDGE_CLASS.get("F4 h-share")
    for key in sorted(EDGE_CLASS, key=len, reverse=True):
        if p.startswith(key) or key in p:
            return EDGE_CLASS[key]
    return ("UNCLASSIFIED", "")


def part_E(repo, report):
    report("")
    report("PART E: the edge harvest (every .echo( call in "
           "interference/, from source)")
    report("-" * 70)
    src_dir = os.path.join(repo, "interference")
    pat = re.compile(
        r"\.echo\(\s*\n?\s*\[\s*\"([^\"]+)\"(?:\s*,\s*\"([^\"]+)\")?\s*\]"
        r".*?,\s*(\d)\s*,\s*\n?\s*\"(FORCED|CANDIDATE)\"",
        re.DOTALL)
    rows = []
    src_files = []
    for dirpath, dirnames, filenames in os.walk(src_dir):
        dirnames[:] = [d for d in dirnames if d != "__pycache__"]
        src_files += [os.path.join(dirpath, f) for f in filenames
                      if f.endswith(".py")]
    for path_fn in sorted(src_files):
        fn = os.path.basename(path_fn)
        text = open(path_fn, encoding="utf-8").read()
        for m in pat.finditer(text):
            path = m.group(1) + (("->" + m.group(2)) if m.group(2)
                                 else "")
            rows.append((fn, _normalise(path), int(m.group(3)),
                         m.group(4)))
    counts = {"EMBEDDING": 0, "INTRA-FACE": 0, "UNCLASSIFIED": 0}
    for fn, path, depth, status in rows:
        cls, why = classify(path)
        counts[cls] = counts.get(cls, 0) + 1
        report(f"  {fn:<18s} d{depth} [{status:<6s}] {path:<28s} "
               f"{cls:<11s} {why[:44]}")
    # parametric inherited edges (masses.py copies lepton_EM terms) are
    # not literal-path calls; note them
    report("  (parametric edges not caught by the literal-path parse: "
           "masses.py inherits the lepton_EM")
    report("   bridge->EM edge per charged lepton, and gravity.py adds "
           "one a1 heat-kernel edge per")
    report("   E8-decomposition channel, dof counts x per-dof a1, "
           "riding the same 14+52+182 inventory;")
    report("   gravity.py's own comment already grounds the scalar "
           "reading in D^2_local = 1, i.e. PART B.)")
    report(f"  totals: {counts}")
    assert counts["UNCLASSIFIED"] == 0, "an edge escaped the taxonomy"
    report("")
    report("  CROSS-DERIVED (edges and selections carried by stated "
           "derivations, each with its witness):")
    for name, form, derivation in CROSS_DERIVED:
        report(f"    {name:<18s} {form}")
        report(f"        = {derivation}")
    return rows, counts


